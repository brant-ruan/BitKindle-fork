/* Test-only fractional reference values from host Math.Pow(2,x). */
static int exp2_reference(void) {
    struct V {
        double x, y;
    };
    struct V v[] = {{-1074.75, 5E-324},
                    {-1074.5, 5E-324},
                    {-1074.25, 5E-324},
                    {-1073.5, 5E-324},
                    {-1022.5, 1.5733648139913585E-308},
                    {-100.125, 7.2338863961376475E-31},
                    {-2.75, 0.14865088937534013},
                    {-0.75, 0.5946035575013605},
                    {-0.125, 0.9170040432046712},
                    {0.125, 1.0905077326652577},
                    {0.25, 1.189207115002721},
                    {0.75, 1.681792830507429},
                    {1.25, 2.378414230005442},
                    {17.5, 185363.80004736633},
                    {100.125, 1.3823827818666394E+30},
                    {1023.5, 1.2711610061536464E+308},
                    {1023.9999999999999, 1.7976931348621742E+308}};

    union {
        double f;
        unsigned long long u;
    } a, b;

    unsigned long long d;
    int i;
    for (i = 0; i < sizeof v / sizeof v[0]; i++) {
        a.f = exp2(v[i].x);
        b.f = v[i].y;
        d = a.u > b.u ? a.u - b.u : b.u - a.u;
        if (d > 1)
            return i + 1;
    }
    return 0;
}
